create or replace function private.write_security_audit(
  target_family_id uuid,
  action_name text,
  target_type_value text default null,
  target_id_value text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not private.authorize_family_access(target_family_id, null, 'read') then return; end if;

  insert into public.security_audit_log(actor_user_id, family_id, action, target_type, target_id)
  values ((select auth.uid()), target_family_id, action_name, target_type_value, target_id_value);
end;
$$;

