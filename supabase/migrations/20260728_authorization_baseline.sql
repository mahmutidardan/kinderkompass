create table if not exists public.security_audit_log (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_user_id uuid references auth.users(id) on delete set null,
  family_id uuid references public.families(id) on delete cascade,
  action text not null check (action in (
    'family_created',
    'invitation_created',
    'invitation_accepted',
    'invitation_revoked',
    'member_removed',
    'child_profiles_changed'
  )),
  target_type text,
  target_id text
);

create index if not exists security_audit_log_family_occurred_idx
on public.security_audit_log(family_id, occurred_at desc);

alter table public.security_audit_log enable row level security;

create or replace function private.authorize_family_access(
  target_family_id uuid,
  target_child_id text default null,
  required_operation text default 'read'
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  actor_role text;
  child_is_known boolean;
begin
  if (select auth.uid()) is null or target_family_id is null then return false; end if;

  select role into actor_role
  from public.family_members
  where family_id = target_family_id and user_id = (select auth.uid());

  if actor_role is null then return false; end if;

  if target_child_id is not null then
    select exists (
      select 1
      from public.family_states state_row
      cross join lateral jsonb_array_elements(coalesce(state_row.state -> 'children', '[]'::jsonb)) as child(value)
      where state_row.family_id = target_family_id
        and child.value ->> 'id' = target_child_id
    ) into child_is_known;
    if not child_is_known then return false; end if;
  end if;

  if required_operation = 'read' then return true; end if;
  if required_operation = 'write' then return actor_role in ('owner', 'guest'); end if;
  if required_operation = 'manage' then return actor_role = 'owner'; end if;
  return false;
end;
$$;

grant usage on schema private to authenticated;
grant execute on function private.authorize_family_access(uuid, text, text) to authenticated;

